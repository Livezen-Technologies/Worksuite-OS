// Copies the setup state machine (shell/src/components/setup-wizard core + recovery planning) into src/machine so
// the service ships it in its own package. The shell copy is canonical; test/machine-sync.test.ts fails when they
// differ. Run after changing the shell copy:  node services/setup/scripts/sync-machine.mjs
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
export const SRC = path.resolve(here, '../../../shell/src/components/setup-wizard')
export const DEST = path.resolve(here, '../src/machine')
export const DIRS = ['core', 'recovery']
export const HEADER = '// GENERATED by services/setup/scripts/sync-machine.mjs from shell/src/components/setup-wizard. Do not edit.\n'

export function expected() {
  const out = new Map()
  for (const d of DIRS) for (const f of readdirSync(path.join(SRC, d)))
    if (f.endsWith('.ts') && !f.endsWith('.test.ts')) out.set(`${d}/${f}`, HEADER + readFileSync(path.join(SRC, d, f), 'utf8'))
  return out
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  rmSync(DEST, { recursive: true, force: true })
  for (const [rel, body] of expected()) { mkdirSync(path.dirname(path.join(DEST, rel)), { recursive: true }); writeFileSync(path.join(DEST, rel), body) }
  console.log(`synced ${expected().size} files into ${path.relative(process.cwd(), DEST)}`)
}
